export type IconName = keyof typeof registry;

/** Allowed icon sizes (NOVA: 16 / 20 / 24 only). */
export type IconSize = 16 | 20 | 24;

export interface IconProps {
  name: IconName;
  /** 16 / 20 / 24. Default 20. */
  size?: IconSize;
  /** Defaults to the current text colour. */
  color?: string;
  strokeWidth?: number;
}

/**
 * The single icon wrapper. lucide-react-native is imported here and nowhere
 * else; screens use `<Icon name="…" />`. Stroke 1.75 by default.
 */
export function Icon({ name, size = 20, color, strokeWidth = 1.75 }: IconProps) {
  const t = useTokens();
  const Cmp = registry[name];
  return <Cmp size={size} color={color ?? t.text} strokeWidth={strokeWidth} />;
}
