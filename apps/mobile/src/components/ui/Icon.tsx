export type IconName = keyof typeof registry;

/** Phosphor icon weight, re-exported so screens never import phosphor directly. */
export type IconWeightProp = IconWeight;

/** Allowed icon sizes. 26 / 28 are reserved for floating chrome (the tab bar). */
export type IconSize = 16 | 20 | 24 | 26 | 28;

export interface IconProps {
  name: IconName;
  /** 16 / 20 / 24 (26 / 28 for the tab bar). Default 20. */
  size?: IconSize;
  /** Defaults to the current text colour. */
  color?: string;
  /** Phosphor weight. Default "bold"; use "fill" for active/selected. */
  weight?: IconWeight;
}

/**
 * The single icon wrapper. phosphor-react-native is imported here and nowhere
 * else; screens use `<Icon name="…" />`. Weight "bold" by default, "fill" for
 * active tab / selected states.
 */
export function Icon({ name, size = 20, color, weight = 'bold' }: IconProps) {
  const t = useTokens();
  const Cmp = registry[name];
  return <Cmp size={size} color={color ?? t.text} weight={weight} />;
}
